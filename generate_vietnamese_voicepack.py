for idx, (fname, text) in enumerate(PROMPTS.items(), 1):
    path = os.path.join(OUTPUT_DIR, fname)
    if os.path.exists(path) and os.path.getsize(path) > 1000:
        continue
    try:
        tts = gTTS(text, lang='vi')
        tts.save(path)
        print(f"[{idx}/{len(PROMPTS)}] {fname} -> {text}")
    except Exception as e:
        print(f"[{idx}/{len(PROMPTS)}] Error on {fname}: {e}")
    time.sleep(0.05)

